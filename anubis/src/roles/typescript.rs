//! Renders a resolved role set as the generated TypeScript module.
//!
//! The output follows the Jalapeno Labs TypeScript conventions (named
//! exports, `as const` lookup tables, no semicolons) and is deterministic:
//! the same roles.yml always renders byte-identical TypeScript, so CI can
//! fail on drift with a plain diff.
//!
//! The module carries the vocabulary rather than anybody's standing: which
//! permissions exist, and what each recommended role grants. What the signed-in
//! person may do in a tenant is resolved by the server from that tenant's own
//! roles, and `can` asks about the permission keys it answered with.

use std::fmt::Write;

use chrono::Datelike;

use crate::roles::RoleSet;

pub(crate) fn render(set: &RoleSet) -> String {
    let year = chrono::Utc::now().year();
    let mut out = String::new();

    // The header matches the repository's license-header lint rule.
    let _ = writeln!(out, "// Copyright © {year} Jalapeno Labs");
    out.push_str(
        "\n\
         // Generated by `anubis roles generate-ts` from config/roles.yml.\n\
         // Do not edit by hand. Edit roles.yml and regenerate.\n\
         \n\
         export type PermissionAction = 'read' | 'create' | 'update' | 'destroy'\n\
         \n",
    );

    out.push_str(
        "// Every permission a role may carry: each model's actions, and the framework's own subjects.\n\
         export const PermissionKeys = [\n",
    );
    for permission in set.vocabulary() {
        let _ = writeln!(out, "  '{}',", escape(&permission.to_string()));
    }
    out.push_str(
        "] as const\n\
         \n\
         export type PermissionKey = typeof PermissionKeys[number]\n\
         \n",
    );

    out.push_str("export type RoleKey =\n");
    for role in set.role_keys() {
        let _ = writeln!(out, "  | '{}'", escape(role));
    }
    out.push('\n');

    out.push_str(
        "// What each role in roles.yml grants: the definition an organization's\n\
         // recommended role follows until it is edited, and what a platform role means.\n\
         export const RoleGrants = {\n",
    );
    for role in set.role_keys() {
        let grants = set.grants(role).into_iter().flatten().collect::<Vec<_>>();
        if grants.is_empty() {
            let _ = writeln!(out, "  {}: {{}},", key(role));
            continue;
        }
        let _ = writeln!(out, "  {}: {{", key(role));
        // The house lint quotes either every key of an object or none, and a
        // namespaced subject (`Billing::Subscription`) always needs quotes.
        let quote_all = grants
            .iter()
            .any(|(model, _actions)| key(model).as_str() != model.as_str());
        for (model, actions) in grants {
            let rendered_actions = actions
                .iter()
                .map(|action| format!("'{}'", action.as_str()))
                .collect::<Vec<_>>()
                .join(", ");
            let rendered_key = if quote_all {
                format!("'{}'", escape(model))
            } else {
                key(model)
            };
            // House style pads array literals: `[ 'read' ]`, not `['read']`.
            let _ = writeln!(out, "    {rendered_key}: [ {rendered_actions} ],");
        }
        out.push_str("  },\n");
    }
    out.push_str(
        "} as const satisfies Record<RoleKey, Partial<Record<string, readonly PermissionAction[]>>>\n\
         \n",
    );

    out.push_str(
        "// Whether the permission keys the server resolved for a tenant allow the action.\n\
         export function can(\n\
         \x20\x20permissions: readonly string[],\n\
         \x20\x20action: PermissionAction,\n\
         \x20\x20model: string,\n\
         ): boolean {\n\
         \x20\x20return permissions.includes(`${model}.${action}`)\n\
         }\n\
         \n",
    );

    out.push_str("// The tiers each role may be granted at.\n");
    out.push_str("export type RoleScope = 'platform' | 'organization' | 'sub_tenant' | 'team'\n\n");
    out.push_str("export const RoleScopes = {\n");
    for role in set.role_keys() {
        let rendered_tiers = set
            .scopes(role)
            .into_iter()
            .flatten()
            .map(|scope| format!("'{}'", scope.as_str()))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(out, "  {}: [ {rendered_tiers} ],", key(role));
    }
    out.push_str("} as const satisfies Record<RoleKey, readonly RoleScope[]>\n\n");

    out.push_str(
        "const scopesByRole: Record<string, readonly RoleScope[] | undefined> = RoleScopes\n\
         \n\
         export function isGrantableAt(role: string, scope: RoleScope): boolean {\n\
         \x20\x20return Boolean(scopesByRole[role]?.includes(scope))\n\
         }\n",
    );

    out
}

/// Renders an object key, quoting only when it is not a plain identifier.
fn key(raw: &str) -> String {
    let plain_identifier = !raw.is_empty()
        && raw
            .chars()
            .next()
            .is_some_and(|first| first.is_ascii_alphabetic() || first == '_' || first == '$')
        && raw.chars().all(|character| {
            character.is_ascii_alphanumeric() || character == '_' || character == '$'
        });

    if plain_identifier {
        raw.to_owned()
    } else {
        format!("'{}'", escape(raw))
    }
}

fn escape(raw: &str) -> String {
    raw.replace('\\', "\\\\").replace('\'', "\\'")
}

#[cfg(test)]
mod tests {
    use crate::roles::RoleSet;

    const BASELINE: &str = "
roles:
  default:
    models:
      Project: [read]
  admin:
    includes: [default]
    models:
      Project: [manage]
  billing:
    scopes: [organization]
    models: {}
  operator:
    scopes: [platform]
    models: {}
";

    #[test]
    fn renders_role_keys_grants_and_the_can_helper() {
        let set = RoleSet::from_yaml(BASELINE).expect("baseline must parse");
        let rendered = set.to_typescript();

        assert!(rendered.contains("| 'admin'"), "got:\n{rendered}");
        assert!(rendered.contains("| 'billing'"), "got:\n{rendered}");
        assert!(
            rendered.contains("Project: [ 'read', 'create', 'update', 'destroy' ],"),
            "got:\n{rendered}"
        );
        assert!(
            rendered.contains("'Billing::Subscription': [ 'update' ],"),
            "the framework's grant to the billing key is visible, got:\n{rendered}"
        );

        assert!(rendered.contains("operator: {},"), "got:\n{rendered}");
        assert!(
            rendered.contains("export function can("),
            "got:\n{rendered}"
        );
        assert!(!rendered.contains(';'), "no semicolons, got:\n{rendered}");
    }

    #[test]
    fn an_object_holding_one_quoted_key_quotes_them_all() {
        let yaml = "
roles:
  billing:
    models:
      Project: [read]
";
        let set = RoleSet::from_yaml(yaml).expect("must parse");
        let rendered = set.to_typescript();

        assert!(
            rendered.contains("    'Billing::Subscription': [ 'update' ],"),
            "got:\n{rendered}"
        );
        assert!(
            rendered.contains("    'Project': [ 'read' ],"),
            "the house lint quotes every key or none, got:\n{rendered}"
        );
    }

    #[test]
    fn renders_the_permission_vocabulary() {
        let set = RoleSet::from_yaml(BASELINE).expect("baseline must parse");
        let rendered = set.to_typescript();

        for key in [
            "'Project.read',",
            "'Project.destroy',",
            "'Tenancy::Membership.update',",
            "'Tenancy::Role.create',",
            "'Billing::Subscription.update',",
        ] {
            assert!(rendered.contains(key), "missing {key}, got:\n{rendered}");
        }
        assert!(
            rendered.contains("export type PermissionKey = typeof PermissionKeys[number]"),
            "got:\n{rendered}"
        );
    }

    #[test]
    fn renders_the_tier_each_role_may_be_granted_at() {
        let set = RoleSet::from_yaml(BASELINE).expect("baseline must parse");
        let rendered = set.to_typescript();

        assert!(
            rendered.contains("billing: [ 'organization' ],"),
            "a declared scope narrows the role, got:\n{rendered}"
        );
        assert!(
            rendered.contains("admin: [ 'organization', 'sub_tenant', 'team' ],"),
            "an undeclared scope means every tenancy tier, got:\n{rendered}"
        );
        assert!(
            rendered.contains("operator: [ 'platform' ],"),
            "the platform tier is reached only by naming it, got:\n{rendered}"
        );
        assert!(
            rendered.contains("export function isGrantableAt("),
            "got:\n{rendered}"
        );
    }

    #[test]
    fn output_is_deterministic() {
        let set = RoleSet::from_yaml(BASELINE).expect("baseline must parse");
        assert_eq!(set.to_typescript(), set.to_typescript());
    }
}
